-- =============================================================================
-- 02_schema.sql
-- Demo e-commerce schema "shop" for the PostgreSQL minor-upgrade lab (16.2 -> 16.3)
--
-- Run:  sudo -u postgres psql -d shopdb -f sql/02_schema.sql
--
-- 7 tables linked by foreign keys, one index of each common kind.
-- Only core PostgreSQL features are used here (no extension required).
-- Extension-based objects are created later in 05_database_objects.sql
-- =============================================================================
\set ON_ERROR_STOP on
\timing on

BEGIN;

DROP SCHEMA IF EXISTS shop CASCADE;
CREATE SCHEMA shop;
COMMENT ON SCHEMA shop IS 'Demo e-commerce schema for PostgreSQL 16 minor upgrade lab';

SET search_path = shop, public;

-- -----------------------------------------------------------------------------
-- 1. Custom types
-- -----------------------------------------------------------------------------
CREATE TYPE shop.order_status AS ENUM
  ('PENDING', 'PAID', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED', 'RETURNED');

CREATE DOMAIN shop.money_amount AS numeric(12,2)
  CHECK (VALUE >= 0);

-- -----------------------------------------------------------------------------
-- 2. Tables
-- -----------------------------------------------------------------------------
CREATE TABLE shop.countries (
    country_code  char(2)      PRIMARY KEY,
    country_name  varchar(100) NOT NULL,
    region        varchar(50)  NOT NULL,
    currency_code char(3)      NOT NULL,
    tax_rate      numeric(5,4) NOT NULL DEFAULT 0 CHECK (tax_rate BETWEEN 0 AND 1)
);

CREATE TABLE shop.categories (
    category_id        integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    parent_category_id integer REFERENCES shop.categories (category_id) ON DELETE SET NULL,  -- self reference
    category_name      varchar(100) NOT NULL,
    slug               varchar(120) NOT NULL
);

CREATE TABLE shop.customers (
    customer_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    varchar(50)  NOT NULL,
    last_name     varchar(50)  NOT NULL,
    email         varchar(255) NOT NULL CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    phone         varchar(20),
    gender        char(1) CHECK (gender IN ('M', 'F', 'O')),
    date_of_birth date,
    country_code  char(2) NOT NULL REFERENCES shop.countries (country_code),
    city          varchar(100) NOT NULL,
    loyalty_tier  varchar(10) NOT NULL DEFAULT 'BRONZE'
                  CHECK (loyalty_tier IN ('BRONZE', 'SILVER', 'GOLD', 'PLATINUM')),
    is_active     boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE shop.products (
    product_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku           varchar(30)  NOT NULL UNIQUE,
    product_name  varchar(200) NOT NULL,
    description   text,
    category_id   integer NOT NULL REFERENCES shop.categories (category_id),
    brand         varchar(60),
    unit_price    shop.money_amount NOT NULL CHECK (unit_price > 0),
    unit_cost     shop.money_amount NOT NULL,
    stock_qty     integer NOT NULL DEFAULT 0 CHECK (stock_qty >= 0),
    attributes    jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_active     boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_products_margin CHECK (unit_cost <= unit_price)
);

CREATE TABLE shop.orders (
    order_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number    varchar(20) NOT NULL UNIQUE,
    customer_id     bigint NOT NULL REFERENCES shop.customers (customer_id),
    order_status    shop.order_status NOT NULL DEFAULT 'PENDING',
    sales_channel   varchar(10) NOT NULL DEFAULT 'WEB'
                    CHECK (sales_channel IN ('WEB', 'MOBILE', 'STORE', 'PARTNER')),
    order_date      timestamptz NOT NULL DEFAULT now(),
    subtotal        shop.money_amount NOT NULL DEFAULT 0,
    discount_amount shop.money_amount NOT NULL DEFAULT 0,
    tax_amount      shop.money_amount NOT NULL DEFAULT 0,
    shipping_fee    shop.money_amount NOT NULL DEFAULT 0,
    total_amount    shop.money_amount NOT NULL DEFAULT 0,
    currency_code   char(3) NOT NULL DEFAULT 'USD',
    updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE shop.order_items (
    order_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      bigint   NOT NULL REFERENCES shop.orders (order_id) ON DELETE CASCADE,
    line_no       smallint NOT NULL CHECK (line_no > 0),
    product_id    bigint   NOT NULL REFERENCES shop.products (product_id),
    quantity      integer  NOT NULL CHECK (quantity > 0),
    unit_price    shop.money_amount NOT NULL,
    discount_pct  numeric(5,2) NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
    line_total    shop.money_amount NOT NULL,
    CONSTRAINT uq_order_items_order_line UNIQUE (order_id, line_no)
);

CREATE TABLE shop.payments (
    payment_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        bigint NOT NULL REFERENCES shop.orders (order_id) ON DELETE CASCADE,
    payment_method  varchar(20) NOT NULL
                    CHECK (payment_method IN ('CREDIT_CARD', 'DEBIT_CARD', 'PAYPAL', 'BANK_TRANSFER', 'CASH_ON_DELIVERY')),
    payment_status  varchar(10) NOT NULL
                    CHECK (payment_status IN ('CAPTURED', 'FAILED', 'REFUNDED')),
    amount          shop.money_amount NOT NULL,
    transaction_ref varchar(40) NOT NULL,
    paid_at         timestamptz NOT NULL
);

-- -----------------------------------------------------------------------------
-- 3. Indexes - one of each kind
--    (PRIMARY KEY / UNIQUE constraints above already create unique B-tree indexes)
-- -----------------------------------------------------------------------------
-- B-tree on a foreign key column
CREATE INDEX idx_order_items_product     ON shop.order_items (product_id);
CREATE INDEX idx_payments_order          ON shop.payments (order_id);
-- Composite B-tree
CREATE INDEX idx_products_category_price ON shop.products (category_id, unit_price);
-- Covering B-tree (INCLUDE) -> index-only scan for a customer's order history
CREATE INDEX idx_orders_customer_date    ON shop.orders (customer_id, order_date DESC)
       INCLUDE (order_status, total_amount);
-- Partial B-tree -> only "open" orders
CREATE INDEX idx_orders_status_open      ON shop.orders (order_date)
       WHERE order_status IN ('PENDING', 'PAID', 'PROCESSING');
-- Unique expression index -> case-insensitive unique e-mail
CREATE UNIQUE INDEX uq_customers_email_lower ON shop.customers (lower(email));
-- GIN on JSONB
CREATE INDEX idx_products_attributes_gin ON shop.products USING gin (attributes jsonb_path_ops);
-- BRIN on an append-only timestamp
CREATE INDEX idx_payments_paid_at_brin   ON shop.payments USING brin (paid_at) WITH (pages_per_range = 64);
-- Hash index -> equality lookup by transaction reference
CREATE INDEX idx_payments_txn_ref_hash   ON shop.payments USING hash (transaction_ref);

-- -----------------------------------------------------------------------------
-- 4. Comments
-- -----------------------------------------------------------------------------
COMMENT ON TABLE shop.countries   IS 'Reference list of countries, currency and VAT rate';
COMMENT ON TABLE shop.categories  IS 'Product category tree (self-referencing parent_category_id)';
COMMENT ON TABLE shop.customers   IS 'Registered customers';
COMMENT ON TABLE shop.products    IS 'Product catalog; attributes stored as JSONB';
COMMENT ON TABLE shop.orders      IS 'Sales order header';
COMMENT ON TABLE shop.order_items IS 'Sales order lines';
COMMENT ON TABLE shop.payments    IS 'Payments of orders';

COMMIT;

\echo 'Schema shop created.'
SELECT table_name FROM information_schema.tables WHERE table_schema = 'shop' ORDER BY 1;
