-- -----------------------------------------------------------------------------
-- 1. Tables
-- -----------------------------------------------------------------------------
CREATE TABLE shop.customers (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       text        NOT NULL,
    full_name   text        NOT NULL,
    country     char(2)     NOT NULL,
    tier        text        NOT NULL DEFAULT 'standard' CHECK (tier IN ('standard','silver','gold')),
    created_at  timestamptz NOT NULL
);

CREATE TABLE shop.products (
    product_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         text           NOT NULL UNIQUE,
    name        text           NOT NULL,
    category    text           NOT NULL,
    price       numeric(10,2)  NOT NULL CHECK (price > 0),
    stock_qty   integer        NOT NULL DEFAULT 0,
    attributes  jsonb          NOT NULL DEFAULT '{}'
);

CREATE TABLE shop.orders (
    order_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint        NOT NULL,
    status       text          NOT NULL CHECK (status IN ('new','paid','shipped','delivered','cancelled')),
    total_amount numeric(12,2) NOT NULL,
    created_at   timestamptz   NOT NULL
);

CREATE TABLE shop.order_items (
    item_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   bigint        NOT NULL,
    product_id bigint        NOT NULL,
    quantity   integer       NOT NULL CHECK (quantity > 0),
    unit_price numeric(10,2) NOT NULL
);

CREATE TABLE shop.payments (
    payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   bigint        NOT NULL,
    method     text          NOT NULL CHECK (method IN ('card','paypal','bank','cod')),
    amount     numeric(12,2) NOT NULL,
    paid_at    timestamptz   NOT NULL
);

CREATE TABLE shop.inventory_movements (
    movement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  bigint      NOT NULL,
    delta       integer     NOT NULL,
    reason      text        NOT NULL,
    meta        jsonb       NOT NULL DEFAULT '{}',
    created_at  timestamptz NOT NULL
);

CREATE TABLE shop.review_votes (
    vote_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id   bigint      NOT NULL,   -- points to shop.product_reviews (no FK on purpose)
    customer_id bigint      NOT NULL,
    is_helpful  boolean     NOT NULL,
    voted_at    timestamptz NOT NULL,
    UNIQUE (review_id, customer_id)
);

