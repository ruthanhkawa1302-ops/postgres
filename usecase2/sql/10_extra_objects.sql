-- Additional tables, indexes, functions, procedure and view for UC02 (~80 MB of new data).
-- ADDITIVE: it does NOT touch shop.product_reviews / fn_review_excerpt / v_review_excerpt
-- (they come from 06). It only drops and recreates its own objects, so it is re-runnable.
--
--   sudo -u postgres psql -d shopdb -f sql/10_extra_objects.sql
--   sudo -u postgres psql -d shopdb -v scale=0.5 -f sql/10_extra_objects.sql   # about half the size
--
-- Requires: schema shop with shop.product_reviews (ids 1..10000) from 06. No extension needed.
-- No foreign keys (same rule as 06). Data is deterministic (no random()).
-- =============================================================================
\set ON_ERROR_STOP on
\timing on
\if :{?scale}
\else
  \set scale 1
\endif

