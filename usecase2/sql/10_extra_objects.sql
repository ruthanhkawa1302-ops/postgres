-- -----------------------------------------------------------------------------
-- 4. Functions, procedure, views. None of them reads the TOAST column product_reviews.body.
-- -----------------------------------------------------------------------------
CREATE FUNCTION shop.fn_customer_order_total(p_customer_id bigint)
RETURNS numeric LANGUAGE sql STABLE AS $$
    SELECT coalesce(sum(total_amount), 0) FROM shop.orders
    WHERE customer_id = p_customer_id AND status <> 'cancelled';
$$;

CREATE FUNCTION shop.fn_top_products(p_limit integer DEFAULT 10)
RETURNS TABLE (product_id bigint, name text, units_sold bigint, revenue numeric)
LANGUAGE sql STABLE AS $$
    SELECT p.product_id, p.name, sum(i.quantity), sum(i.quantity * i.unit_price)
    FROM shop.order_items i JOIN shop.products p USING (product_id)
    GROUP BY p.product_id, p.name
    ORDER BY 4 DESC, 1
    LIMIT p_limit;
$$;

CREATE FUNCTION shop.fn_review_rating_summary(p_product_id bigint)
RETURNS TABLE (reviews bigint, avg_rating numeric, helpful_votes bigint)
LANGUAGE sql STABLE AS $$
    SELECT count(DISTINCT r.review_id),
           round(avg(r.rating), 2),
           count(v.vote_id) FILTER (WHERE v.is_helpful)
    FROM shop.product_reviews r
    LEFT JOIN shop.review_votes v ON v.review_id = r.review_id
    WHERE r.product_id = p_product_id;
$$;

CREATE FUNCTION shop.fn_monthly_revenue(p_year integer)
RETURNS TABLE (month integer, orders bigint, revenue numeric)
LANGUAGE sql STABLE AS $$
    SELECT extract(month FROM created_at)::int, count(*), sum(total_amount)
    FROM shop.orders
    WHERE created_at >= make_date(p_year, 1, 1) AND created_at < make_date(p_year + 1, 1, 1)
      AND status <> 'cancelled'
    GROUP BY 1 ORDER BY 1;
$$;

CREATE PROCEDURE shop.sp_cancel_order(p_order_id bigint)
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE shop.orders SET status = 'cancelled'
    WHERE order_id = p_order_id AND status IN ('new','paid');
    IF NOT FOUND THEN
        RAISE EXCEPTION 'order % not found or cannot be cancelled', p_order_id;
    END IF;
    DELETE FROM shop.payments WHERE order_id = p_order_id;
END $$;

CREATE VIEW shop.v_product_sales AS
SELECT p.product_id, p.sku, p.category, count(i.item_id) AS lines, coalesce(sum(i.quantity), 0) AS units
FROM shop.products p LEFT JOIN shop.order_items i USING (product_id)
GROUP BY p.product_id, p.sku, p.category;

CREATE VIEW shop.v_review_votes_summary AS
SELECT review_id, count(*) AS votes, count(*) FILTER (WHERE is_helpful) AS helpful
FROM shop.review_votes GROUP BY review_id;

