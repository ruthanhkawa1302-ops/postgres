-- =============================================================================
-- 06_toast_review_objects.sql
-- Product reviews with long, non-ASCII text (stored out of line in TOAST) and a simple
-- function that cuts an excerpt with substring(). On PostgreSQL 15.16 this function
-- is expected to fail for part of the rows (regression of the CVE-2026-2006 fix, fixed in 15.17).
--
-- Run on 15.6 (database shopdb, UTF8). This is the only data of UC02:
--   sudo -u postgres psql -d shopdb -f sql/06_toast_review_objects.sql
--
-- Re-runnable (drops and recreates the table). Standalone: no other table is needed.
-- =============================================================================
\set ON_ERROR_STOP on
\timing on

CREATE SCHEMA IF NOT EXISTS shop;
SET search_path = shop, public;

DROP VIEW  IF EXISTS shop.v_review_excerpt;
DROP TABLE IF EXISTS shop.product_reviews CASCADE;

-- -----------------------------------------------------------------------------
-- 1. Table. EXTERNAL = out of line in TOAST but NOT compressed, so substring() can read
--    only the first bytes of the value (a "slice") instead of the whole text.
-- -----------------------------------------------------------------------------
CREATE TABLE shop.product_reviews (
    review_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   bigint   NOT NULL,
    customer_id  bigint   NOT NULL,
    rating       smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    body         text     NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE shop.product_reviews ALTER COLUMN body SET STORAGE EXTERNAL;
CREATE INDEX idx_product_reviews_product ON shop.product_reviews (product_id);

-- -----------------------------------------------------------------------------
-- 2. Data. Review 1 is a fixed test row (only 3-byte characters), the others are
--    ~3.5 KB English text with typographic characters (’ — … €), so every value is TOASTed.
--    No random(): the data is the same on every run.
-- -----------------------------------------------------------------------------
INSERT INTO shop.product_reviews (product_id, customer_id, rating, body)
OVERRIDING SYSTEM VALUE
VALUES (1, 1, 5, repeat('’', 2000));

WITH w AS (
    SELECT ARRAY['It’s','great','value','—','works','well','don’t','buy','€20','battery',
                 'very','good','quality','shipping','fast','I’m','happy','…','price','solid',
                 'arrived','on','time','would','recommend','the','box','was','damaged','but'] AS words
)
INSERT INTO shop.product_reviews (product_id, customer_id, rating, body)
SELECT 1 + (g * 7919) % 1000,
       1 + (g * 104729) % 1000,
       1 + (g % 5),
       (SELECT string_agg(w.words[1 + (g * 31 + i * 17) % array_length(w.words, 1)], ' ')
        FROM generate_series(1, 600) i)
FROM generate_series(2, 10000) g, w;

SELECT setval(pg_get_serial_sequence('shop.product_reviews', 'review_id'), 10000);

-- -----------------------------------------------------------------------------
-- 3. Business function: short excerpt of a review (product page, e-mail digest)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION shop.fn_review_excerpt(p_review_id bigint, p_len integer DEFAULT 40)
RETURNS text
LANGUAGE sql STABLE
AS $$
    SELECT substring(body, 1, p_len) FROM shop.product_reviews WHERE review_id = p_review_id;
$$;

CREATE OR REPLACE VIEW shop.v_review_excerpt AS
SELECT review_id, product_id, rating, substring(body, 1, 40) AS excerpt
FROM shop.product_reviews;

VACUUM (ANALYZE) shop.product_reviews;

-- -----------------------------------------------------------------------------
-- 4. Check: values are TOASTed and the function works (expected on 15.6: 0 failures)
-- -----------------------------------------------------------------------------
SELECT count(*)                                             AS reviews,
       count(*) FILTER (WHERE pg_column_size(body) > 2000)  AS big_values,
       (SELECT reltoastrelid::regclass FROM pg_class WHERE oid = 'shop.product_reviews'::regclass) AS toast_table
FROM shop.product_reviews;
SELECT shop.fn_review_excerpt(1, 10) AS excerpt_review_1, shop.fn_review_excerpt(2) AS excerpt_review_2;
